create table labels (
    id         bigint generated by default as identity primary key,
    name       varchar(1000) not null,
    created_at timestamp     not null default now(),
    updated_at timestamp     not null default now(),
    constraint uk_labels_name unique (name)
);

create table tasks_labels (
    task_id  bigint not null,
    label_id bigint not null,
    primary key (task_id, label_id),
    constraint fk_tasks_labels_task  foreign key (task_id)  references tasks (id) on delete cascade,
    constraint fk_tasks_labels_label foreign key (label_id) references labels (id)
);

create index idx_tasks_labels_label_id on tasks_labels (label_id);
